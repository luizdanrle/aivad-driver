export const SUPPORTED_LANGUAGE_MAP = Object.fromEntries(
  SUPPORTED_LANGUAGES.map((l) => [l.code, l])
) as Record<string, SupportedLanguageMeta>;

export function isSupportedLanguageCode(code: string): boolean {
  return Boolean(SUPPORTED_LANGUAGE_MAP[code]);
}

export function getLanguageMeta(code: string): SupportedLanguageMeta {
  if (SUPPORTED_LANGUAGE_MAP[code]) return SUPPORTED_LANGUAGE_MAP[code];
  const base = code.split('-')[0].toLowerCase();
  const byBase = SUPPORTED_LANGUAGES.find(
    (l) => l.code.toLowerCase() === base || l.code.toLowerCase().startsWith(`${base}-`)
  );
  return byBase ?? SUPPORTED_LANGUAGE_MAP['pt-PT'];
}

export function isRtlLanguage(code: string): boolean {
  const normalized = (code || '').toLowerCase();
  if (normalized === 'ar' || normalized.startsWith('ar-') || normalized === 'ur' || normalized.startsWith('ur-')) {
    return true;
  }
  return getLanguageMeta(code).dir === 'rtl';
}

