const BASE_KEYS = Object.keys(PT_PT);

export function translateKey(languageCode: string, key: string): string {
  const meta = getLanguageMeta(languageCode);
  const direct = I18N_DICTIONARY[meta.code]?.[key];
  if (direct) return direct;
  for (const fb of meta.fallbackChain) {
    const val = I18N_DICTIONARY[fb]?.[key];
    if (val) return val;
  }
  return I18N_DICTIONARY['en-GB'][key] ?? I18N_DICTIONARY['pt-PT'][key] ?? key;
}

export function auditI18nCoverage(): {
  supportedCount: number;
  baseKeysCount: number;
  rtlLanguages: string[];
  allLanguagesResolvable: boolean;
  missingDirectKeysByLang: Record<string, string[]>;
} {
  const missingDirectKeysByLang: Record<string, string[]> = {};
  let allLanguagesResolvable = true;

  for (const lang of SUPPORTED_LANGUAGES) {
    const dict = I18N_DICTIONARY[lang.code] ?? {};
    const missingDirect = BASE_KEYS.filter((k) => !dict[k]);
    if (missingDirect.length > 0) {
      missingDirectKeysByLang[lang.code] = missingDirect;
    }
    for (const k of BASE_KEYS) {
      const resolved = translateKey(lang.code, k);
      if (!resolved || resolved === k) {
        allLanguagesResolvable = false;
      }
    }
  }

  return {
    supportedCount: SUPPORTED_LANGUAGES.length,
    baseKeysCount: BASE_KEYS.length,
    rtlLanguages: SUPPORTED_LANGUAGES.filter((l) => l.dir === 'rtl').map((l) => l.code),
    allLanguagesResolvable,
    missingDirectKeysByLang,
  };
}
